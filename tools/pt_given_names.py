"""Build the Portuguese given-name list rules/O6's veto reads under
locales.PT_BR and locales.PT_PT (#1453).

WHY THIS IS IN THE TREE. `Policy(two_family_names=True)` (rules/O6)
moves the name word before the family into the family, and in "Ana
Beatriz Costa" that word is a given name. A reader settles it by
vocabulary, as tools/es_given_names.py's lists settle it for Spanish
(#959), so O6 leaves a listed given name where it stands. No census
table of given names by count was found for Portugal or Brazil, so
the list is measured on the names ORCID's holders split themselves:

- ORCID's public data file (CC0), as tools/differential/local_orcid.py
  extracts it into the `orcid-researchers` local corpus: each holder's
  given-names box and family-name box, and the country they work or
  live in.

A word's given uses are the given boxes holding it, its family uses
the family boxes holding it, less a word written right after a word
the default reads as a particle ("da Paz"), a surname unit O6 takes
whole and the veto never reads, over the records of Portugal and
Brazil past the first HELD_OUT of each country in the corpus's order:
`config_diff.py score --cap HELD_OUT` scores the first HELD_OUT, so
the records that build the list are never the records it is scored on
(decisions/O6, 2026-11-19). One list serves both countries: lists cut
from each country's records alone read fewer of its own held-out
records than the pooled one (the same entry).

A word is a candidate where it has at least MIN_USES uses and at
least SHARE of them are given uses; the list is every candidate,
ranked by given uses. Words the default vocabulary lists as a
particle, a conjunction, a title or a suffix are left out, as the
Spanish tool leaves them out (its `excluded_words`), and so are
words of one letter, which write an initial. The floor and SHARE are
measured choices (decisions/O6, 2026-11-19): a change to either is a
cutoff change, decided against the same per-country measurement.
Every word the cut keeps was read by hand before the list shipped;
REMOVED holds each word that reading took out, with why.

Each listed word written with ç is also listed with c where that
spelling passes the same share test over every use the c stands for,
as the Spanish lists list an ñ word with n (#1081): data from systems
without the letter writes "Goncalo" for Gonçalo, and `given_name_key`
keeps the cedilla, so the fold runs one way through generated entries.

Standard output is the list: each ranked word with its uses, then
each c spelling (a `c` row with its summed uses and share); a refused
c spelling is reported on standard error. `--words` prints any words'
tallied uses.

    uv run python tools/pt_given_names.py
    uv run python tools/pt_given_names.py --write
    uv run python tools/pt_given_names.py --min-uses 3 --share 0.8
    uv run python tools/pt_given_names.py --countries PT --min-uses 5 \\
        | awk '$1 ~ /^[0-9]+$/ {print $2}' > LIST   # a candidate list
    uv run python tools/pt_given_names.py --words Augusto Socorro

The corpus is read from the local-corpus cache ($NAMEPARSER_TOOLS_CACHE
or ~/.cache/nameparser-tools); `uv run python
tools/differential/local_corpora.py fetch orcid-researchers` builds it.
"""
from __future__ import annotations

import argparse
import sys
from collections import Counter
from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE / "differential"))
import es_given_names  # noqa: E402  (a sibling script, not a package)

MODULE = HERE.parent / "nameparser" / "locales" / "_pt_given_names.py"
SOURCE = "orcid-researchers"
#: The countries whose records build the list, as ORCID writes them.
COUNTRIES = ("PT", "BR")
#: The records of each country set aside for scoring, the first in the
#: corpus's order: config_diff.py score's --cap reads the same ones.
HELD_OUT = 3000
#: The decided floor and share (decisions/O6, 2026-11-19).
MIN_USES = 5
SHARE = 0.7
#: Words the cut keeps that the hand reading took out, each with why
#: (decisions/O6, 2026-11-19).
REMOVED: Mapping[str, str] = {}

BEGIN = "# -- BEGIN generated by tools/pt_given_names.py; edit the tool, not this block --"
END = "# -- END generated --"

fold = es_given_names.fold


def tally(records: Iterable[Mapping[str, str]], countries: Sequence[str],
          held_out: int, after: Iterable[str]
          ) -> tuple[Counter[str], Counter[str]]:
    """Each word's given and family uses over `records` of `countries`
    past the first `held_out` of each, both boxes filled; a family word
    written right after one of `after` is not counted (a unit O6 takes
    whole). A word holding anything but letters is left out, as the
    Spanish tool's `words` leaves it out."""
    given: Counter[str] = Counter()
    family: Counter[str] = Counter()
    seen: Counter[str] = Counter()
    particles = frozenset(after)
    for record in records:
        country = record.get("country", "")
        if country not in countries:
            continue
        seen[country] += 1
        if seen[country] <= held_out:
            continue
        g, f = record.get("given", "").strip(), record.get("family", "").strip()
        if not (g and f):
            continue
        given.update(es_given_names.words(g))
        written = es_given_names.words(f)
        family.update(w for i, w in enumerate(written)
                      if not (i and written[i - 1] in particles))
    return given, family


def select(given: Counter[str], family: Counter[str], excluded: set[str],
           min_uses: int = MIN_USES, share: float = SHARE,
           removed: Iterable[str] = ()) -> list[str]:
    """The words of at least `min_uses` uses at least `share` of which
    are given uses, most given uses first, less `excluded` (the default
    vocabulary's non-name readings), `removed` and words of one letter."""
    out = set(removed)
    return sorted(
        (w for w, g in given.items()
         if len(w) > 1 and w not in excluded and w not in out
         and g + family[w] >= min_uses and g >= share * (g + family[w])),
        key=lambda w: (-given[w], w))


def c_spelling_uses(ranked: list[str], given: Counter[str], family: Counter[str],
                    excluded: set[str]) -> list[tuple[str, int, int]]:
    """Each candidate c spelling of a `ranked` word written with ç, in
    rank order, with its given and family uses summed over every
    spelling it stands for: an ASCII writer turns Gonçalo and a Goncalo
    alike into "Goncalo", so both count. A spelling already listed or
    `excluded` is no candidate."""
    def c(word: str) -> str:
        return word.replace("ç", "c")
    merged_given: Counter[str] = Counter()
    merged_family: Counter[str] = Counter()
    for word, count in given.items():
        merged_given[c(word)] += count
    for word, count in family.items():
        merged_family[c(word)] += count
    listed = set(ranked)
    return [(c(word), merged_given[c(word)], merged_family[c(word)])
            for word in ranked
            if c(word) != word and c(word) not in listed and c(word) not in excluded]


def c_spellings(ranked: list[str], given: Counter[str], family: Counter[str],
                excluded: set[str], share: float = SHARE) -> list[str]:
    """The candidate c spellings (`c_spelling_uses`) passing the
    `share` test over their summed uses, in rank order."""
    return [word for word, g, f in c_spelling_uses(ranked, given, family, excluded)
            if g >= share * (g + f)]


def render(ranked: list[str], spellings: list[str]) -> str:
    def rows(words: list[str]) -> str:
        lines = [", ".join(f'"{w}"' for w in words[i:i + 8])
                 for i in range(0, len(words), 8)]
        return "\n".join(f"    {line}," for line in lines)
    return (f"{BEGIN}\n_RANKED = (\n{rows(ranked)}\n)\n"
            f"_C_SPELLINGS = (\n{rows(spellings)}\n)\n{END}")


def rewrite(module_text: str, block: str) -> str:
    start, end = module_text.find(BEGIN), module_text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{MODULE} has no generated block to replace")
    return module_text[:start] + block + module_text[end + len(END):]


def load_records() -> list[dict[str, str]]:
    """The corpus's fielded records, in its order."""
    import local_agreement
    import local_corpora
    return list(local_agreement.records(local_corpora.require(SOURCE)))


def particles() -> set[str]:
    """The default's particles, folded as the list is: a family word
    written after one is not counted."""
    from nameparser import Lexicon
    return {fold(w) for entry in Lexicon.default()._sets.particles for w in entry.split()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write", action="store_true",
                        help="rewrite the generated block in the list's module")
    parser.add_argument("--min-uses", type=int, default=MIN_USES)
    parser.add_argument("--share", type=float, default=SHARE)
    parser.add_argument("--held-out", type=int, default=HELD_OUT,
                        help="records of each country left for scoring")
    parser.add_argument("--countries", default=",".join(COUNTRIES),
                        help="the countries whose records build the list")
    parser.add_argument("--words", nargs="+", metavar="WORD",
                        help="print these words' given and family uses "
                             "as tallied, and nothing else")
    args = parser.parse_args(argv)
    countries = tuple(args.countries.split(","))
    if args.write and (args.min_uses, args.share, args.held_out, countries) != (
            MIN_USES, SHARE, HELD_OUT, COUNTRIES):
        parser.error("--write writes the decided cut; change the constants "
                     "in the tool, not the flags")
    excluded = es_given_names.excluded_words()
    given, family = tally(load_records(), countries, args.held_out, particles())
    if not given:
        raise SystemExit(f"no record of {', '.join(countries)} past the first "
                         f"{args.held_out} holds both boxes")
    if args.words:
        for word in map(fold, args.words):
            print(f"{word:20} given {given[word]:>7,}  family {family[word]:>7,}")
        return 0
    ranked = select(given, family, excluded, args.min_uses, args.share, REMOVED)
    spellings = c_spellings(ranked, given, family, excluded, args.share)
    for i, word in enumerate(ranked, 1):
        print(f"{i:5}  {word:20} given {given[word]:>7,}  family {family[word]:>7,}")
    for word, g, f in c_spelling_uses(ranked, given, family, excluded):
        kept = word in spellings
        print(f"    c  {word:20} given {g:>7,}  family {f:>7,}  "
              f"{g / (g + f):.1%} given, {'kept' if kept else 'refused'}",
              file=sys.stdout if kept else sys.stderr)
    for word, why in REMOVED.items():
        print(f"removed  {word:20} given {given[word]:>7,}  family {family[word]:>7,}"
              f"  {why}", file=sys.stderr)
    covered = sum(given[w] for w in ranked)
    print(f"{len(ranked)} words, {covered / sum(given.values()):.1%} of "
          "given-word uses", file=sys.stderr)
    if args.write:
        MODULE.write_text(rewrite(MODULE.read_text(encoding="utf-8"),
                                  render(ranked, spellings)), encoding="utf-8")
        print(f"wrote {MODULE}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
