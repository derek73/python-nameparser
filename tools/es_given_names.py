"""Build the Spanish given-name list rules/O6's veto reads.

WHY THIS IS IN THE TREE. `Policy(two_family_names=True)` (rules/O6)
moves the name word before the family into the family, and in "José
Luis Pérez" that word is a given name: most of what the switch gets
wrong is that shape (#959). A reader settles it by vocabulary, since
Spanish given names are a concentrated set and few words are common in
both roles, so O6 leaves a listed given name where it stands. The list
is a coverage decision with a cutoff, like locales.ZH's surnames, not a
set of words judged one by one, so it is derived here rather than kept
by hand:

- Instituto Nacional de Estadística (INE), "Frecuencias de nombres":
  every given name borne by at least 20 residents of Spain, by sex,
  from the annual population census of 1 January 2025
  (nombres_por_edad_media.xlsx). Names are written whole, upper case
  and without acute accents ("JOSE LUIS", "MARIA CARMEN"); Ñ and Ç
  are kept.
- INE, "Frecuencias de apellidos": every surname borne as a first
  surname by at least 20 residents, with its count as first and as
  second surname, from the same census (apellidos_frecuencia.xls).

Both are published under INE's general licence, Creative Commons
Attribution 4.0 (https://www.ine.es/aviso_legal, "Reutilización de la
información contenida en este sitio web"), which asks the reuser to
cite "Elaboración propia con datos extraídos del sitio web del INE:
www.ine.es" and the date the data were last updated.

A word's given uses are the bearers of every listed name holding it,
summed over both sexes; its surname uses, the bearers of every listed
surname holding it, first and second surname together, less a surname
holding it behind a particle ("de Miguel"), a surname unit O6 takes
whole and the veto never reads. A word is a
candidate where at least SHARE of its uses are given-name uses, and the
candidates are ranked by given uses; the list is the first TOP. Words
the default vocabulary reads as something other than a name (a
particle, a conjunction, a title or a suffix) are left out, since O6
never takes a word as its own unit that any of those readings claim,
and the disjointness test in tests/v2/test_es_given_names.py holds the
shipped list to that. The cutoff and SHARE are measured choices
(decisions/O6, 2026-10-30): a change to either is a cutoff change,
decided against the same per-country measurement.

    uv run --with openpyxl --with xlrd python tools/es_given_names.py
    uv run --with openpyxl --with xlrd python tools/es_given_names.py --write
    uv run --with openpyxl --with xlrd python tools/es_given_names.py --top 500

Sources are cached outside the repository, in $NAMEPARSER_TOOLS_CACHE
or ~/.cache/nameparser-tools (shared with name_usage.py); --refresh
fetches them again, and both tables move when INE publishes a new
census year.
"""
from __future__ import annotations

import argparse
import sys
import urllib.request
from collections import Counter
from collections.abc import Collection, Iterable
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import name_usage  # noqa: E402  (a sibling script, not a package)

MODULE = (Path(__file__).parents[1] / "nameparser" / "locales"
          / "_es_given_names.py")
#: The decided cutoff and share (decisions/O6, 2026-10-30).
TOP = 1000
SHARE = 0.9

NAMES_URL = "https://www.ine.es/daco/daco42/nombyapel/nombres_por_edad_media.xlsx"
NAMES_FILE = "ine_nombres_2025.xlsx"
SURNAMES_URL = "https://www.ine.es/daco/daco42/nombyapel/apellidos_frecuencia.xls"
SURNAMES_FILE = "ine_apellidos_2025.xls"

BEGIN = "# -- BEGIN generated by tools/es_given_names.py; edit the tool, not this block --"
END = "# -- END generated --"


def fold(word: str) -> str:
    """`word` as the list is written and matched: the parse's own key,
    `_vocab.given_name_key`, which lower-cases and drops the acute and
    grave accents and the diaeresis, keeping the tilde on n and the
    cedilla on c, as INE writes names. One function, so the list and
    the lookup cannot fold apart."""
    from nameparser._pipeline._vocab import given_name_key
    return given_name_key(word)


def words(name: str) -> list[str]:
    """A name's words, folded; a word holding anything but letters (an
    apostrophe, a stray mark) is left out, being no word a name list
    can carry whole."""
    return [w for w in (fold(part) for part in name.split()) if w.isalpha()]


def tally(rows: Iterable[tuple[str, int]],
          after: Collection[str] = ()) -> Counter[str]:
    """Each word's bearers over (name, bearers) rows, less a word
    written right after one of `after`: a surname written behind a
    particle ("de Miguel") is a surname unit O6 takes whole and the
    veto never reads, so it says nothing about whether the bare word
    is a surname."""
    counts: Counter[str] = Counter()
    for name, bearers in rows:
        written = words(name)
        for i, word in enumerate(written):
            if not (i and written[i - 1] in after):
                counts[word] += bearers
    return counts


def select(given: Counter[str], surname: Counter[str], excluded: set[str],
           top: int = TOP, share: float = SHARE) -> list[str]:
    """The `top` words with the most given uses among those at least
    `share` of whose uses are given-name uses, most-borne first, less
    `excluded` (the default vocabulary's non-name readings) and words
    of one letter, which write an initial."""
    ranked = sorted(
        (w for w, g in given.items()
         if len(w) > 1 and w not in excluded
         and g >= share * (g + surname[w])),
        key=lambda w: (-given[w], w))
    return ranked[:top]


def excluded_words() -> set[str]:
    """Every word the default vocabulary reads as a particle, a
    conjunction, a title or a suffix, folded as the list is."""
    from nameparser import Lexicon
    lex = Lexicon.default()
    pool = (lex.particles | lex.conjunctions | lex.titles
            | lex.titles_ambiguous | lex.suffix_acronyms | lex.suffix_words)
    return {fold(w) for entry in pool for w in entry.split()}


def render(ranked: list[str]) -> str:
    rows = [", ".join(f'"{w}"' for w in ranked[i:i + 8])
            for i in range(0, len(ranked), 8)]
    body = "\n".join(f"    {row}," for row in rows)
    return f"{BEGIN}\n_RANKED = (\n{body}\n)\n{END}"


def rewrite(module_text: str, block: str) -> str:
    start, end = module_text.find(BEGIN), module_text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{MODULE} has no generated block to replace")
    return module_text[:start] + block + module_text[end + len(END):]


# -- sources --------------------------------------------------------------

def _cached(url: str, name: str, refresh: bool, magic: bytes) -> Path:
    """The cached copy of `url`, fetched where absent or on --refresh;
    an answer that does not open with the format's `magic` bytes (an
    error page) is refused rather than cached."""
    path = name_usage.cache_dir() / name
    if refresh or not path.exists():
        request = urllib.request.Request(
            url, headers={"User-Agent": name_usage.USER_AGENT})
        with urllib.request.urlopen(request, timeout=120) as response:
            data: bytes = response.read()
        if not data.startswith(magic):
            raise ValueError(f"{url} returned no spreadsheet; "
                             f"it began {data[:80]!r}")
        path.write_bytes(data)
    return path


def load_names(refresh: bool) -> list[tuple[str, int]]:
    """INE's given names, both sexes, as (name, bearers). The rows open
    under a header row whose first cell is "Orden"."""
    import openpyxl
    path = _cached(NAMES_URL, NAMES_FILE, refresh, b"PK")
    rows: list[tuple[str, int]] = []
    workbook = openpyxl.load_workbook(path, read_only=True)
    for sheet in workbook.worksheets:
        body = False
        for row in sheet.iter_rows(values_only=True):
            if body and row[1]:
                rows.append((str(row[1]), int(row[2])))
            body = body or row[0] == "Orden"
    if len(rows) < 50_000:
        raise ValueError(f"{path} holds {len(rows)} names; the 2025 "
                         "tables hold over 63,000")
    return rows


def load_surnames(refresh: bool) -> list[tuple[str, int]]:
    """INE's surnames as (surname, bearers as first plus as second
    surname). A count INE withholds is written ".." and read as 0."""
    import xlrd
    path = _cached(SURNAMES_URL, SURNAMES_FILE, refresh,
                   b"\xd0\xcf\x11\xe0")
    rows: list[tuple[str, int]] = []
    workbook = xlrd.open_workbook(path)
    for sheet in workbook.sheets():
        body = False
        for i in range(sheet.nrows):
            row = sheet.row_values(i)
            if body and row[1]:
                count = sum(int(v) for v in row[2:4] if isinstance(v, float))
                rows.append((str(row[1]), count))
            body = body or row[0] == "Orden"
    if len(rows) < 80_000:
        raise ValueError(f"{path} holds {len(rows)} surnames; the 2025 "
                         "tables hold over 86,000")
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write", action="store_true",
                        help=f"rewrite the generated block in {MODULE.name}")
    parser.add_argument("--refresh", action="store_true",
                        help="fetch the sources again")
    parser.add_argument("--top", type=int, default=TOP)
    parser.add_argument("--share", type=float, default=SHARE)
    args = parser.parse_args(argv)
    excluded = excluded_words()
    given = tally(load_names(args.refresh))
    surname = tally(load_surnames(args.refresh), after=excluded)
    ranked = select(given, surname, excluded, args.top, args.share)
    for i, word in enumerate(ranked, 1):
        print(f"{i:5}  {word:20} given {given[word]:>9,}  "
              f"surname {surname[word]:>8,}")
    covered = sum(given[w] for w in ranked)
    print(f"{len(ranked)} words, {covered / sum(given.values()):.1%} of "
          "given-word uses", file=sys.stderr)
    if args.write:
        MODULE.write_text(rewrite(MODULE.read_text(encoding="utf-8"),
                                  render(ranked)), encoding="utf-8")
        print(f"wrote {MODULE}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
